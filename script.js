function setupWorkDrag() {
  if (!workTrack) return;
  const dragSurface = workViewport || workTrack;
  let dragging = false;
  let startX = 0;
  let startScroll = 0;
  let lastX = 0;
  let lastTime = 0;
  let velocity = 0;
  let inertiaFrame = null;
  let moved = false;
  let pendingProject = null;

  const stopInertia = () => {
    if (!inertiaFrame) return;
    window.cancelAnimationFrame(inertiaFrame);
    inertiaFrame = null;
  };

  const runInertia = () => {
    velocity *= 0.95;
    workTrack.scrollLeft += velocity * 16;
    updateWorkScroller();
    if (Math.abs(velocity) < 0.1) {
      inertiaFrame = null;
      return;
    }
    inertiaFrame = window.requestAnimationFrame(runInertia);
  };

  dragSurface.addEventListener("pointerdown", (event) => {
    stopInertia();
    dragging = true;
    moved = false;
    velocity = 0;
    pendingProject = event.target.closest("[data-project]")?.dataset.project || null;
    startX = event.clientX;
    lastX = event.clientX;
    lastTime = event.timeStamp;
    startScroll = workTrack.scrollLeft;
    workTrack.classList.add("is-dragging");
    dragSurface.setPointerCapture(event.pointerId);
  });

  dragSurface.addEventListener("pointermove", (event) => {
    if (!dragging) return;
    const delta = event.clientX - startX;
    const deltaTime = Math.max(16, event.timeStamp - lastTime);
    const deltaX = lastX - event.clientX;
    if (Math.abs(delta) > 6) moved = true;
    velocity = deltaX / deltaTime;
    workTrack.scrollLeft = startScroll - delta;
    lastX = event.clientX;
    lastTime = event.timeStamp;
    updateWorkScroller();
  });

  const endDrag = (event) => {
    if (!dragging) return;
    dragging = false;
    workTrack.classList.remove("is-dragging");
    if (event?.pointerId != null && dragSurface.hasPointerCapture?.(event.pointerId)) {
      dragSurface.releasePointerCapture(event.pointerId);
    }
    if (moved) {
      ignoreWorkClick = true;
      inertiaFrame = window.requestAnimationFrame(runInertia);
      window.setTimeout(() => {
        ignoreWorkClick = false;
      }, 80);
    } else if (pendingProject) {
      ignoreWorkClick = true;
      openProject(pendingProject);
      window.setTimeout(() => {
        ignoreWorkClick = false;
      }, 80);
    }
    pendingProject = null;
  };

  dragSurface.addEventListener("pointerup", endDrag);
  dragSurface.addEventListener("pointercancel", endDrag);
  dragSurface.addEventListener("pointerleave", endDrag);
}

